"use client";

import { useState, useEffect } from "react";
import { useSession } from "next-auth/react";
import { useRouter } from "next/navigation";
import { toast } from "sonner";
import api from "@/lib/axios";
import {
  Search,
  Plus,
  Trophy,
  CheckCircle2,
  XCircle,
  X,
  Loader2,
  AlertTriangle,
  Edit,
  Trash2,
  Unlock,
  Lock,
  Save,
  List,
  ChevronLeft,
  ChevronRight,
} from "lucide-react";

export interface Round {
  idRound: number;
  roundNumber: number;
  active: boolean;
  submissionsOpen: boolean;
  groupCount: number;
  eliminationAmount?: number;
  specialRound?: boolean;
}

// Omit idRound for create payload since it's generated by the backend
type FormDataPayload = Omit<Round, "idRound">;

const INITIAL_FORM_STATE: FormDataPayload = {
  roundNumber: undefined as unknown as number, // Type assertion to satisfy TypeScript
  active: false,
  submissionsOpen: false,
  groupCount: 1,
  eliminationAmount: undefined,
  specialRound: false,
};

export default function RoundsPage() {
  const { data: session, status: authStatus } = useSession();
  const router = useRouter();

  const userRole = (session?.user as any)?.role || "USER";
  const isAdmin = userRole === "ADMIN";
  const isStaff = userRole === "STAFF";

  // State management
  const [rounds, setRounds] = useState<Round[]>([]);
  const [isLoading, setIsLoading] = useState(true);
  const [searchTerm, setSearchTerm] = useState("");

  // Modals state
  const [isCreateModalOpen, setIsCreateModalOpen] = useState(false);
  const [roundToDelete, setRoundToDelete] = useState<Round | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [formData, setFormData] = useState<FormDataPayload>(INITIAL_FORM_STATE);

  // Pagination
  const [currentPage, setCurrentPage] = useState(1);
  const ITEMS_PER_PAGE = 10;

  useEffect(() => {
    if (authStatus === "authenticated") {
      fetchRounds();
    }
  }, [authStatus]);

  useEffect(() => {
    setCurrentPage(1);
  }, [searchTerm]);

  const fetchRounds = async () => {
    try {
      setIsLoading(true);
      const res = await api.get("/rounds");

      // Sort by round number ascending
      const sortedRounds = res.data.sort((a: Round, b: Round) => a.roundNumber - b.roundNumber);
      setRounds(sortedRounds);
    } catch (error: any) {
      // Error handled by interceptor
    } finally {
      setIsLoading(false);
    }
  };

  const filteredRounds = rounds.filter((round) =>
    round.roundNumber.toString().includes(searchTerm),
  );

  const totalPages = Math.ceil(filteredRounds.length / ITEMS_PER_PAGE);

  const currentRounds = filteredRounds.slice(
    (currentPage - 1) * ITEMS_PER_PAGE,
    currentPage * ITEMS_PER_PAGE,
  );

  const handleOpenCreate = () => {
    setFormData(INITIAL_FORM_STATE);
    setIsCreateModalOpen(true);
  };

  const handleSubmit = async (e: React.SubmitEvent<HTMLFormElement>) => {
    e.preventDefault();

    if (formData.roundNumber === undefined) return;

    try {
      setIsSubmitting(true);

      // By default new rounds are created as inactive
      const createPayload: FormDataPayload = {
        roundNumber: formData.roundNumber,
        active: false,
        submissionsOpen: false,
        groupCount: formData.groupCount,
        eliminationAmount: formData.eliminationAmount,
        specialRound: formData.specialRound,
      };

      const res = await api.post("/rounds", createPayload);

      const newRound = res.data;

      // Update local state with the new round
      setRounds((prevRounds) =>
        [...prevRounds, newRound].sort((a, b) => a.roundNumber - b.roundNumber),
      );

      toast.success("Round created successfully.", {
        description: `The round ${newRound.roundNumber} has been added to the system.`,
        closeButton: true,
      });

      setIsCreateModalOpen(false);
      setFormData(INITIAL_FORM_STATE);
    } catch (error: any) {
      // Error handled by interceptor
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleDeleteConfirm = async () => {
    if (!roundToDelete) return;

    try {
      setIsSubmitting(true);

      await api.delete(`/rounds/${roundToDelete.idRound}`);

      setRounds((prevRounds) => prevRounds.filter((r) => r.idRound !== roundToDelete.idRound));

      toast.success("Round deleted successfully.", {
        description: `The round ${roundToDelete.roundNumber} has been removed from the system.`,
        closeButton: true,
      });

      setRoundToDelete(null);
    } catch (error: any) {
      // Error handled by interceptor
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div className="space-y-6 relative">
      {/* Header Section */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-white">Round Management</h1>
          <p className="text-[#80848E] text-sm mt-1">View and manage rounds for the competition.</p>
        </div>

        {isAdmin && (
          <button
            onClick={handleOpenCreate}
            className="bg-[#5865F2] hover:bg-[#4752C4] text-white px-4 py-2 rounded-md font-medium flex items-center justify-center transition-colors shadow-lg"
          >
            <Plus className="w-4 h-4 mr-2" />
            Add Round
          </button>
        )}
      </div>

      {/* Toolbar (Search) */}
      <div className="bg-[#2B2D31] p-4 rounded-t-lg border border-[#1E1F22] flex items-center">
        <div className="relative flex-1 max-w-md">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-[#80848E]" />
          <input
            type="text"
            placeholder="Search round number..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            className="w-full bg-[#1E1F22] border-none text-[#DBDEE1] text-sm rounded-md pl-10 pr-4 py-2 focus:ring-1 focus:ring-[#5865F2] focus:outline-none placeholder:text-[#80848E]"
          />
        </div>
      </div>

      {/* Data Table */}
      <div className="bg-[#2B2D31] border border-t-0 border-[#1E1F22] overflow-x-auto">
        {isLoading ? (
          <div className="flex flex-col items-center justify-center h-64 text-[#80848E]">
            <Loader2 className="w-8 h-8 animate-spin text-[#5865F2] mb-4" />
            <p>Loading rounds...</p>
          </div>
        ) : (
          <table className="w-full text-left text-sm text-[#DBDEE1] block md:table">
            <thead className="hidden md:table-header-group text-xs text-[#80848E] uppercase bg-[#1E1F22]/50 border-b border-[#1E1F22]">
              <tr>
                <th className="px-6 py-4 font-semibold md:whitespace-nowrap">Round Number</th>
                <th className="px-6 py-4 font-semibold md:whitespace-nowrap">Status</th>
                <th className="px-6 py-4 font-semibold md:whitespace-nowrap">Submissions</th>
                {(isAdmin || isStaff) && (
                  <th className="px-6 py-4 font-semibold text-right md:whitespace-nowrap">
                    Actions
                  </th>
                )}
              </tr>
            </thead>
            <tbody className="block md:table-row-group">
              {currentRounds.length > 0 ? (
                currentRounds.map((round) => (
                  <tr
                    key={round.idRound}
                    className="block md:table-row border-b border-[#1E1F22] hover:bg-[#35373C]/50 transition-colors p-4 md:p-0"
                  >
                    {/* Round Number */}
                    <td className="flex justify-between items-center md:table-cell md:px-6 md:py-4 mb-3 md:mb-0 md:whitespace-nowrap">
                      <span className="md:hidden text-xs font-semibold text-[#80848E] uppercase">
                        Round
                      </span>
                      <div className="font-medium text-white flex items-center gap-3">
                        <div className="w-8 h-8 rounded-full bg-[#5865F2]/20 flex items-center justify-center text-[#5865F2]">
                          <Trophy className="w-4 h-4 shrink-0" />
                        </div>
                        Round {round.roundNumber}
                      </div>
                    </td>

                    {/* Active Status */}
                    <td className="flex justify-between items-center md:table-cell md:px-6 md:py-4 mb-3 md:mb-0 md:whitespace-nowrap">
                      <span className="md:hidden text-xs font-semibold text-[#80848E] uppercase">
                        Status
                      </span>
                      <span
                        className={`inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-medium border ${
                          round.active
                            ? "bg-emerald-500/10 text-emerald-400 border-emerald-500/20"
                            : "bg-red-500/10 text-red-400 border-red-500/20"
                        }`}
                      >
                        {round.active ? (
                          <CheckCircle2 className="w-3 h-3 shrink-0" />
                        ) : (
                          <XCircle className="w-3 h-3 shrink-0" />
                        )}
                        <span className="mt-px leading-none">
                          {round.active ? "Active" : "Inactive"}
                        </span>
                      </span>
                    </td>

                    {/* Submissions Status */}
                    <td className="flex justify-between items-center md:table-cell md:px-6 md:py-4 mb-4 md:mb-0 md:whitespace-nowrap">
                      <span className="md:hidden text-xs font-semibold text-[#80848E] uppercase">
                        Submissions
                      </span>
                      <span
                        className={`inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-medium border ${
                          round.submissionsOpen
                            ? "bg-[#5865F2]/10 text-[#5865F2] border-[#5865F2]/20"
                            : "bg-yellow-500/10 text-yellow-400 border-yellow-500/20"
                        }`}
                      >
                        {round.submissionsOpen ? (
                          <Unlock className="w-3 h-3 shrink-0" />
                        ) : (
                          <Lock className="w-3 h-3 shrink-0" />
                        )}
                        <span className="mt-px leading-none">
                          {round.submissionsOpen ? "Open" : "Closed"}
                        </span>
                      </span>
                    </td>

                    {(isAdmin || isStaff) && (
                      <td className="flex justify-end md:table-cell md:px-6 md:py-4 border-t border-[#35373C] md:border-t-0 pt-3 md:pt-0">
                        <div className="flex justify-end gap-3 w-full md:w-auto">
                          <button
                            onClick={() =>
                              router.push(`/management/rounds/${round.idRound}/detail`)
                            }
                            className="text-emerald-400 hover:text-emerald-500 font-medium transition-colors inline-flex items-center text-sm"
                          >
                            <List className="w-4 h-4 mr-1" /> Detail
                          </button>
                          {isAdmin && (
                            <>
                              <button
                                onClick={() => router.push(`/management/rounds/${round.idRound}`)}
                                className="text-[#5865F2] hover:text-[#4752C4] font-medium transition-colors inline-flex items-center text-sm"
                              >
                                <Edit className="w-4 h-4 mr-1" /> Config
                              </button>
                              <button
                                onClick={() => setRoundToDelete(round)}
                                className="text-red-400 hover:text-red-500 font-medium transition-colors inline-flex items-center text-sm"
                              >
                                <Trash2 className="w-4 h-4 mr-1" /> Delete
                              </button>
                            </>
                          )}
                        </div>
                      </td>
                    )}
                  </tr>
                ))
              ) : (
                <tr>
                  <td
                    colSpan={isAdmin ? 4 : 3}
                    className="px-6 py-8 text-center text-[#80848E] block md:table-cell"
                  >
                    No rounds found.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        )}
      </div>

      {/* Pagination Controls */}
      {!isLoading && filteredRounds.length > 0 && (
        <div className="bg-[#1E1F22] p-4 rounded-b-lg border border-t-0 border-[#1E1F22] flex flex-col sm:flex-row items-center justify-between gap-4">
          <div className="text-sm text-[#80848E] text-center sm:text-left">
            Showing{" "}
            <span className="font-medium text-white">{(currentPage - 1) * ITEMS_PER_PAGE + 1}</span>{" "}
            to{" "}
            <span className="font-medium text-white">
              {Math.min(currentPage * ITEMS_PER_PAGE, filteredRounds.length)}
            </span>{" "}
            of <span className="font-medium text-white">{filteredRounds.length}</span> rounds
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => setCurrentPage((prev) => Math.max(prev - 1, 1))}
              disabled={currentPage === 1}
              className="p-2 rounded-md bg-[#2B2D31] text-[#DBDEE1] border border-[#35373C] hover:bg-[#35373C] disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              <ChevronLeft className="w-4 h-4" />
            </button>
            <div className="text-sm font-medium text-[#DBDEE1] px-4">
              Page {currentPage} of {totalPages}
            </div>
            <button
              onClick={() => setCurrentPage((prev) => Math.min(prev + 1, totalPages))}
              disabled={currentPage === totalPages}
              className="p-2 rounded-md bg-[#2B2D31] text-[#DBDEE1] border border-[#35373C] hover:bg-[#35373C] disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
            >
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}

      {/* Add Round Modal */}
      {isCreateModalOpen && (
        <div className="fixed inset-0 bg-black/60 backdrop-blur-sm flex items-center justify-center z-50 p-4">
          <div className="bg-[#2B2D31] rounded-xl border border-[#1E1F22] w-full max-w-sm shadow-2xl overflow-hidden">
            <div className="flex items-center justify-between p-5 border-b border-[#1E1F22]">
              <h2 className="text-lg font-bold text-white">Create New Round</h2>
              <button
                onClick={() => setIsCreateModalOpen(false)}
                className="text-[#80848E] hover:text-white transition-colors"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <form onSubmit={handleSubmit} className="p-5 space-y-4">
              <div>
                <label className="block text-xs font-semibold text-[#80848E] uppercase mb-1.5">
                  Round Number
                </label>
                <input
                  type="number"
                  min="1"
                  required
                  value={formData.roundNumber || ""}
                  onChange={(e) =>
                    setFormData({ ...formData, roundNumber: Number(e.target.value) })
                  }
                  className="w-full bg-[#1E1F22] border border-[#1E1F22] text-[#DBDEE1] rounded-md px-3 py-2 focus:border-[#5865F2] focus:ring-1 focus:ring-[#5865F2] outline-none transition-all"
                  placeholder="e.g. 1"
                />
              </div>
              <div>
                <label className="block text-xs font-semibold text-[#80848E] uppercase mb-1.5">
                  Total Groups
                </label>
                <input
                  type="number"
                  min="1"
                  required
                  value={formData.groupCount}
                  onChange={(e) =>
                    setFormData({ ...formData, groupCount: Math.max(1, Number(e.target.value)) })
                  }
                  className="w-full bg-[#1E1F22] border border-[#1E1F22] text-[#DBDEE1] rounded-md px-3 py-2 focus:border-[#5865F2] outline-none"
                />
              </div>
              <div>
                <label className="block text-xs font-semibold text-[#80848E] uppercase mb-1.5">
                  Elimination Amount{" "}
                  <span className="text-[#80848E] italic font-normal lowercase">
                    (optional on creation)
                  </span>
                </label>
                <input
                  type="number"
                  min="0"
                  value={
                    formData.eliminationAmount || formData.eliminationAmount === 0
                      ? formData.eliminationAmount.toString()
                      : ""
                  }
                  onChange={(e) =>
                    setFormData({
                      ...formData,
                      eliminationAmount:
                        e.target.value || e.target.value === "0"
                          ? Math.max(0, Number(e.target.value))
                          : undefined,
                    })
                  }
                  className="w-full bg-[#1E1F22] border border-[#1E1F22] text-[#DBDEE1] rounded-md px-3 py-2 focus:border-[#5865F2] outline-none"
                />
              </div>
              <div>
                <label className="flex items-center gap-3 bg-[#1E1F22] p-3 rounded-md border border-[#35373C] cursor-pointer group hover:border-[#4E5058] transition-colors">
                  <div className="relative flex items-center justify-center w-5 h-5 shrink-0 bg-[#2B2D31] border border-[#4E5058] rounded group-hover:border-[#DBDEE1] transition-colors mt-0.5 sm:mt-0">
                    <input
                      type="checkbox"
                      checked={formData.specialRound}
                      onChange={(e) => setFormData({ ...formData, specialRound: e.target.checked })}
                      className="peer opacity-0 absolute w-full h-full cursor-pointer"
                    />
                    <div className="hidden peer-checked:block text-[#5865F2]">
                      <svg viewBox="0 0 14 14" fill="none" className="w-3.5 h-3.5">
                        <path
                          d="M3 8L6 11L11 3.5"
                          strokeWidth={2}
                          strokeLinecap="round"
                          strokeLinejoin="round"
                          stroke="currentColor"
                        ></path>
                      </svg>
                    </div>
                  </div>
                  <div>
                    <p className="font-bold text-white text-sm group-hover:text-[#E67E22] transition-colors">
                      Special Round
                    </p>
                    <p className="text-xs text-[#80848E]">
                      Contestants will only be able to select tracks from their Collection.
                    </p>
                  </div>
                </label>
              </div>

              <div className="pt-4 flex items-center justify-end gap-3">
                <button
                  type="button"
                  onClick={() => setIsCreateModalOpen(false)}
                  className="px-4 py-2 text-sm font-medium text-[#DBDEE1] hover:underline"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={isSubmitting}
                  className="bg-[#5865F2] hover:bg-[#4752C4] text-white px-6 py-2 rounded-md text-sm font-medium transition-all flex items-center gap-2 disabled:opacity-50 disabled:cursor-not-allowed"
                >
                  {isSubmitting ? (
                    <Loader2 className="w-4 h-4 animate-spin mr-2" />
                  ) : (
                    <Save className="w-4 h-4" />
                  )}
                  {isSubmitting ? "Creating..." : "Create"}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* Delete Confirmation Modal */}
      {roundToDelete && (
        <div className="fixed inset-0 bg-black/60 backdrop-blur-sm flex items-center justify-center z-50 p-4">
          <div className="bg-[#2B2D31] rounded-xl border border-[#1E1F22] w-full max-w-sm shadow-2xl overflow-hidden">
            <div className="p-6 text-center">
              <div className="w-16 h-16 rounded-full bg-red-500/10 flex items-center justify-center mx-auto mb-4">
                <AlertTriangle className="w-8 h-8 text-red-500" />
              </div>
              <h2 className="text-xl font-bold text-white mb-2">Delete Round</h2>
              <p className="text-[#80848E] text-sm">
                Are you sure you want to delete{" "}
                <span className="font-bold text-[#DBDEE1]">round {roundToDelete.roundNumber}</span>?
                This action cannot be undone.
              </p>
            </div>

            <div className="bg-[#1E1F22] p-4 flex items-center justify-end gap-3">
              <button
                type="button"
                onClick={() => setRoundToDelete(null)}
                disabled={isSubmitting}
                className="px-4 py-2 text-sm font-medium text-[#DBDEE1] hover:underline disabled:opacity-50 disabled:cursor-not-allowed"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={handleDeleteConfirm}
                disabled={isSubmitting}
                className="bg-red-500 hover:bg-red-600 text-white px-6 py-2 rounded-md text-sm font-medium transition-all flex items-center gap-2 disabled:opacity-50 disabled:cursor-not-allowed"
              >
                {isSubmitting ? (
                  <Loader2 className="w-4 h-4 animate-spin mr-2" />
                ) : (
                  <Trash2 className="w-4 h-4" />
                )}
                {isSubmitting ? "Deleting..." : "Delete"}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
